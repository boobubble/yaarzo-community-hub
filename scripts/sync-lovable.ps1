param(
    [Parameter(Mandatory=$true)]
    [string]$ZipPath
)

$ErrorActionPreference = "Stop"

$RepoRoot = (Resolve-Path (Join-Path $PSScriptRoot "..")).Path
$TempRoot = Join-Path $RepoRoot ".lovable-sync-temp"
$ReviewRoot = Join-Path $RepoRoot ".lovable-review"

Write-Host ""
Write-Host "=== Yaarzo Lovable Sync ===" -ForegroundColor Cyan

if (-not (Test-Path $ZipPath)) {
    throw "Lovable ZIP not found: $ZipPath"
}

if (Test-Path $TempRoot) {
    Remove-Item $TempRoot -Recurse -Force
}

New-Item -ItemType Directory -Force $TempRoot | Out-Null
New-Item -ItemType Directory -Force $ReviewRoot | Out-Null

Write-Host "[1/6] Extracting Lovable ZIP..."
Expand-Archive -Path $ZipPath -DestinationPath $TempRoot -Force

$SourceRoot = $TempRoot

# Handle ZIPs containing one top-level project folder.
$children = @(Get-ChildItem $TempRoot)

if (
    $children.Count -eq 1 -and
    $children[0].PSIsContainer -and
    (Test-Path (Join-Path $children[0].FullName "src"))
) {
    $SourceRoot = $children[0].FullName
}

if (-not (Test-Path (Join-Path $SourceRoot "src"))) {
    throw "Invalid Lovable ZIP: src folder not found."
}

Write-Host "[2/6] Protecting Yaarzo backend/auth/chat integration..."

# index.tsx contains our live CodyChat + Supabase integration.
# Never overwrite it automatically.
$LovableIndex = Join-Path $SourceRoot "src\routes\index.tsx"

if (Test-Path $LovableIndex) {
    Copy-Item `
        $LovableIndex `
        (Join-Path $ReviewRoot "index.lovable.tsx") `
        -Force
}

# Keep latest Lovable CSS/theme design.
$LovableStyles = Join-Path $SourceRoot "src\styles.css"

if (Test-Path $LovableStyles) {
    Copy-Item `
        $LovableStyles `
        (Join-Path $RepoRoot "src\styles.css") `
        -Force
}

# Save Lovable plan files for reference without touching runtime code.
$LovablePlan = Join-Path $SourceRoot ".lovable\plan"

if (Test-Path $LovablePlan) {
    $TargetPlan = Join-Path $RepoRoot ".lovable\plan"
    New-Item -ItemType Directory -Force $TargetPlan | Out-Null
    Copy-Item "$LovablePlan\*" $TargetPlan -Recurse -Force
}

Write-Host "[3/6] Saving Lovable UI reference..."

# Keep selected UI files available for review.
$ReviewSrc = Join-Path $ReviewRoot "src"

if (Test-Path $ReviewSrc) {
    Remove-Item $ReviewSrc -Recurse -Force
}

New-Item -ItemType Directory -Force $ReviewSrc | Out-Null

$LovableComponents = Join-Path $SourceRoot "src\components"

if (Test-Path $LovableComponents) {
    Copy-Item `
        $LovableComponents `
        (Join-Path $ReviewSrc "components") `
        -Recurse `
        -Force
}

Write-Host "[4/6] Cleaning temporary extraction..."
Remove-Item $TempRoot -Recurse -Force

Set-Location $RepoRoot

Write-Host "[5/6] Running production build..." -ForegroundColor Yellow

npm run build

if ($LASTEXITCODE -ne 0) {
    throw "Build failed. Nothing should be committed or pushed."
}

# routeTree is generated by TanStack and may change just from build/dev.
git restore src/routeTree.gen.ts 2>$null

Write-Host "[6/6] Git changes:" -ForegroundColor Yellow
git status --short

Write-Host ""
Write-Host "=== Sync completed successfully ===" -ForegroundColor Green
Write-Host "Lovable index reference:"
Write-Host "  .lovable-review\index.lovable.tsx"
Write-Host ""
Write-Host "Protected:"
Write-Host "  Supabase auth"
Write-Host "  CodyChat APIs"
Write-Host "  registered Bridge"
Write-Host "  guest sessions"
Write-Host "  live public chat"
Write-Host "  .env"
Write-Host ""
Write-Host "No commit or push was performed."